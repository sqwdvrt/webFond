def footer(canvas, doc):
    canvas.saveState()
    width, _ = A4
    canvas.setStrokeColor(LINE)
    canvas.setLineWidth(0.4)
    canvas.line(21 * mm, 15 * mm, width - 21 * mm, 15 * mm)
    canvas.setFont("LegalArial", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(21 * mm, 10 * mm, "ФОНД «БЫТЬ ДОБРУ» | ПРОЕКТ ДОКУМЕНТА")
    canvas.drawRightString(width - 21 * mm, 10 * mm, f"Страница {doc.page}")
    canvas.restoreState()


